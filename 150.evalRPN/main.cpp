using namespace std;

// ===================== 答题区域 =====================
// 150. 逆波兰表达式求值（Evaluate Reverse Polish Notation）· 栈 · Medium
//
// 「栈」主题里最直白的一道：**后缀表达式天生就是给栈准备的**。
//   20「有效的括号」是用栈做「匹配」，
//   155「最小栈」是用栈维护「元信息」，
//   这题是用栈做「求值」—— 三种味道完全不同，但都靠同一个 LIFO 语义。
//
//   核心思路一句话：
//       从左往右扫；遇到数字就压栈；遇到运算符就弹出两个数、算完再压回去。
//       扫完之后，栈里剩下的唯一那个数就是答案。
//
//   为什么不用管优先级和括号？因为后缀表达式已经把优先级**编码进顺序**了：
//   "2 1 + 3 *" 和 "(2 + 1) * 3" 是同一件事。
//   编译器内部也是这么干的：先把中缀表达式转成后缀（调度场算法），再求值。
//
//   三个坑（按踩到的概率排序）：
//
//     坑 1 · **弹出顺序：先弹出的是右操作数**
//        int b = st.top(); st.pop();   // 先弹出 -> 右操作数
//        int a = st.top(); st.pop();   // 后弹出 -> 左操作数
//        st.push(a - b);               // 是 a - b，不是 b - a！
//      加法和乘法交换律救了你，所以**示例 1（"2 1 + 3 *"）永远抓不到这个 bug**。
//      必须专门拿减法/除法试 —— 下面「减法顺序」「除法顺序」几组用例就是干这个的。
//
//     坑 2 · **负号 vs 减号**：token "-11" 以 '-' 开头，但它是**数字**；
//      token "-" 才是运算符。所以不能只看第一个字符：
//        · 写法一（推荐，直白）：if (t == "+" || t == "-" || t == "*" || t == "/") 是运算符
//        · 写法二：if (t.size() > 1 || isdigit(t[0])) 是数字
//        · 反例：用 isdigit(t[0]) 判断数字 —— "-11" 的 '-' 不是数字字符，
//          于是会被当成减号，栈里只剩一个数，弹出第二个数时就崩了
//
//     坑 3 · **除法向零截断**：题目要求 -7 / 2 = -3（向零截断），不是向下取整的 -4。
//      C++（C++11 起）的整数除法**本来就是向零截断**，所以 `a / b` 直接用就对：
//           -7 /  2  == -3   ✓（不是 -4）
//          -7 / -2  ==  3   ✓
//           6 / -132 ==  0   ✓  ← 示例 3 就靠这一步；
//                                如果按向下取整算成 -1，最后答案会从 22 变成 7
//      ★ 注意别的语言不一定这样：Python 的 -7 // 2 是 -4（向下取整），
//        所以别照抄 Python 题解去"补符号修正"，在 C++ 里反而会写错。
//        也不要图省事用 double 再强转（大数会丢精度，虽然本题数值小看不出）。
//
//   复杂度：时间 O(n)，空间 O(n)，n = token 个数（≤ 10^4）。
//   每个 token 只进出栈一次，所以是**一趟扫描**，没有嵌套循环。
//
//   面试追问：
//     · 输入改成中缀表达式（"1+2*3"）怎么办？→ 双栈 / 调度场算法转后缀，或递归下降。
//       这就是 224 / 227「基本计算器」的考点
//     · 会不会溢出？→ 题目里每个数都在 [-200, 200]，测试数据的中间结果在 int 范围内；
//       要更保险可以用 long long，但这里没必要
//     · 为什么这题非栈不可？→ 后缀表达式的计算顺序是"最近的两个操作数先算"，
//       正好就是后进先出；用队列（FIFO）就做不到
//
//   同族题：224 基本计算器（Hard，括号 + 优先级）、227 基本计算器 II、
//           772 基本计算器 III（会员）、394 字符串解码、71 简化路径、1190 反转括号间的子串
class Solution
{
public:
    int evalRPN(vector<string> &tokens)
    {
        // TODO: 在这里写你的解法

        stack<int> nums;

        for (string s : tokens)
        {
            if (s == "+" || s == "-" || s == "*" || s == "/")
            {
                int n1 = nums.top();
                nums.pop();
                int n2 = nums.top();
                nums.pop();

                if (s == "+")
                    nums.push(n2 + n1);

                if (s == "-")
                    nums.push(n2 - n1);

                if (s == "*")
                    nums.push(n2 * n1);

                if (s == "/")
                    nums.push(n2 / n1);
            }
            else
                nums.push(stoi(s));
        }

        return nums.top();
    }
};
