// ----------------- 以下为辅助函数与测试骨架，无需修改 -----------------

// 单条测试用例
struct TestCase
{
    string name;           // 用例名称
    vector<string> tokens; // 输入：后缀表达式
    int expected;          // 期望结果
};

// 把 token 列表格式化成 [2 1 + 3 *]，过长时截断
static string joinTokens(const vector<string> &v, size_t limit = 24)
{
    string s = "[";
    for (size_t i = 0; i < v.size() && i < limit; ++i)
    {
        if (i)
            s += " ";
        s += v[i];
    }
    if (v.size() > limit)
        s += " …（共 " + to_string(v.size()) + " 个 token）";
    return s + "]";
}

// 运行一条用例，打印一行信息，返回该用例是否通过
static bool runCase(const TestCase &c)
{
    int actual = 0;

    try
    {
        Solution sol;
        vector<string> tokens = c.tokens; // 传副本：万一解法改动了入参，打印时也不受影响
        actual = sol.evalRPN(tokens);
    }
    catch (const exception &e)
    {
        cout << "[失败] " << c.name << "  抛出异常: " << e.what() << endl;
        return false;
    }

    bool pass = (actual == c.expected);

    cout << (pass ? "[通过] " : "[失败] ") << c.name
         << "  token 数 " << c.tokens.size() << "\n"
         << "       tokens   = " << joinTokens(c.tokens) << "\n"
         << "       期望     = " << c.expected << "\n"
         << "       实际     = " << actual << endl;

    return pass;
}

int main()
{
#ifdef _WIN32
    SetConsoleOutputCP(CP_UTF8); // 让控制台按 UTF-8 输出，避免中文乱码
#endif

    // 题目给出的 3 个示例
    const vector<TestCase> sampleCases = {
        {"示例 1", {"2", "1", "+", "3", "*"}, 9},
        {"示例 2", {"4", "13", "5", "/", "+"}, 6},
        {"示例 3", {"10", "6", "9", "3", "+", "-11", "*", "/", "*", "17", "+", "5", "+"}, 22},
    };

    // 额外的边界与补充用例
    vector<TestCase> extraCases = {
        // 只有一个数：栈里从头到尾就一个元素，最容易验证基本流程
        {"单个数字", {"18"}, 18},

        // 坑 1：弹出顺序。这两个用例互为镜像，只要反了必挂一条
        {"减法顺序（5 - 3）", {"5", "3", "-"}, 2},
        {"减法顺序反过来（3 - 5，抓 b - a）", {"3", "5", "-"}, -2},

        // 坑 3：除法向零截断（四种符号组合，一次把方向全钉死）
        {"除法：7 / (-2) 应为 -3 不是 -4", {"7", "-2", "/"}, -3},
        {"除法：(-7) / 2 应为 -3 不是 -4", {"-7", "2", "/"}, -3},
        {"除法：(-7) / (-2) = 3", {"-7", "-2", "/"}, 3},
        {"除法：2 / (-7) 向零截断为 0", {"2", "-7", "/"}, 0},

        // 坑 2：负号 vs 减号
        {"单独的负数字面量（'-' 开头但不是运算符）", {"-11"}, -11},
        {"负数字面量参与除法：(-11) / (-3) = 3", {"-11", "-3", "/"}, 3},
        {"负数与减法混用：3 - (-4) 再乘 (-5)", {"3", "-4", "-", "-5", "*"}, -35},

        // 多运算符连用 + 边界数值
        {"多运算符连用：(3+4)*2/7 = 2", {"3", "4", "+", "2", "*", "7", "/"}, 2},
        {"混合运算：10-2 再 *3 再 +(-4)", {"10", "2", "-", "3", "*", "-4", "+"}, 20},
        {"边界值：200 * 200", {"200", "200", "*"}, 40000},
        {"边界值：(-200) * (-200)", {"-200", "-200", "*"}, 40000},

        // 0 参与的两种运算
        {"0 当被除数：0 / 5 = 0", {"0", "5", "/"}, 0},
        {"0 参与减法：0 - 5 = -5", {"0", "5", "-"}, -5},
    };

    // 长序列压力用例：9999 个 token —— 这已经是题目上界（10^4）之内**能取到的最大值**
    //   为什么凑不到 10000：只含二元运算符的后缀表达式里，
    //   操作数个数 p 与运算符个数 q 必须满足 p = q + 1（最后栈里恰好剩 1 个值），
    //   于是 token 总数 = p + q = 2q + 1 **必定是奇数**；10000 是偶数，构不出来。
    //   构造方式：先 "2 2 *" 得到 4（占 3 个 token），再重复 4998 次「压 1 再相加」
    //   结果 = 4 + 4998 = 5002，token 数 = 3 + 4998 * 2 = 9999
    //   另外：如果实现里藏了 O(n^2) 的写法（比如每个 token 都重扫一遍栈），这里会明显变慢
    TestCase big;
    big.name = "长序列压力（9999 个 token，合法后缀表达式的上限）";
    big.tokens = {"2", "2", "*"};
    for (int i = 0; i < 4998; ++i)
    {
        big.tokens.push_back("1");
        big.tokens.push_back("+");
    }
    big.expected = 5002;
    extraCases.push_back(big);

    size_t passed = 0;
    size_t total = 0;

    cout << "================ 题目示例 ================" << endl;
    for (const auto &c : sampleCases)
    {
        ++total;
        if (runCase(c))
            ++passed;
    }

    cout << endl
         << "================ 补充用例 ================" << endl;
    for (const auto &c : extraCases)
    {
        ++total;
        if (runCase(c))
            ++passed;
    }

    cout << endl
         << "================ 结果统计 ================" << endl;
    cout << "共 " << total << " 个用例，通过 " << passed
         << " 个，失败 " << (total - passed) << " 个。" << endl;
    cout << (passed == total ? "全部通过 ✔" : "存在失败用例 ✘") << endl;

    return 0;
}
