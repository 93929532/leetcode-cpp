// 把 9 行字符串转成题目要求的 vector<vector<char>>，顺便校验用例数据本身没写错
static vector<vector<char>> toBoard(const vector<string>& lines) {
    if (lines.size() != 9) {
        throw runtime_error("用例数据错误：不是 9 行");
    }
    vector<vector<char>> board;
    for (const string& row : lines) {
        if (row.size() != 9) {
            throw runtime_error("用例数据错误：有一行不是 9 列");
        }
        board.push_back(vector<char>(row.begin(), row.end()));
    }
    return board;
}

// 一行式打印（9 行用 | 连接），便于在输出里一眼扫过整块棋盘
static string compactBoard(const vector<string>& lines) {
    string s;
    for (size_t i = 0; i < lines.size(); ++i) {
        if (i) s += "|";
        s += lines[i];
    }
    return s;
}

