struct TestCase {
    string name;          // 用例名称
    vector<string> board; // 9 行 × 9 列，'.' 表示空格
    bool expected;        // 期望是否合法
};

// 运行一条用例，打印一行信息，返回该用例是否通过
static bool runCase(const TestCase& c) {
    bool actual = false;
    try {
        vector<vector<char>> board = toBoard(c.board);   // 解法收的是非 const 引用，给一份副本
        Solution sol;
        actual = sol.isValidSudoku(board);
    }
    catch (const exception& e) {
        cout << "[失败] " << c.name << "  抛出异常: " << e.what() << endl;
        return false;
    }

    bool pass = (actual == c.expected);

    if (pass) {
        cout << "[通过] " << c.name
             << "  期望: " << boolalpha << c.expected << "  实际: " << actual << noboolalpha
             << "  board = " << compactBoard(c.board) << endl;
    } else {
        // 失败时把棋盘摊成 9 行打印，方便直接找冲突在哪
        cout << "[失败] " << c.name
             << "  期望: " << boolalpha << c.expected << "  实际: " << actual << noboolalpha << "\n";
        for (const string& row : c.board) {
            cout << "       " << row << "\n";
        }
        cout << "       （上面是这块棋盘，'.' 为空格）" << endl;
    }
    return pass;
}

